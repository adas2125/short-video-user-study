"""RQ1 continuation-intention study prototype backed by PostgreSQL.

For local development, set DATABASE_URL to a PostgreSQL connection URL, then run:
    flask --app app run --debug
"""

from __future__ import annotations

import json
import os
import secrets
from datetime import datetime, timezone
from pathlib import Path
from random import Random
from typing import Any

import psycopg
from flask import Flask, Response, abort, g, jsonify, render_template, request, session
from psycopg import IntegrityError
from psycopg.rows import dict_row


BASE_DIR = Path(__file__).resolve().parent
STIMULI_PATH = BASE_DIR / "stimuli.json"
DATABASE_URL = os.environ.get("DATABASE_URL")

app = Flask(__name__)
# Set STUDY_SECRET_KEY in Render before deploying.
app.config["SECRET_KEY"] = os.environ.get("STUDY_SECRET_KEY", "local-prototype-only-change-me")


SCHEMA_STATEMENTS = (
    """
    CREATE TABLE IF NOT EXISTS sessions (
        id TEXT PRIMARY KEY,
        trial_order_json TEXT NOT NULL,
        current_position INTEGER NOT NULL DEFAULT 0,
        started_at TEXT NOT NULL,
        completed_at TEXT
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS trials (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        session_id TEXT NOT NULL REFERENCES sessions(id),
        position INTEGER NOT NULL,
        video_id TEXT NOT NULL,
        video_title TEXT NOT NULL,
        youtube_id TEXT NOT NULL,
        probe_plan_json TEXT NOT NULL,
        created_at TEXT NOT NULL,
        ended_at TEXT,
        UNIQUE(session_id, position)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS responses (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        trial_id BIGINT NOT NULL REFERENCES trials(id),
        probe_index INTEGER NOT NULL,
        planned_probe_time DOUBLE PRECISION NOT NULL,
        probe_category TEXT NOT NULL,
        choice TEXT NOT NULL CHECK(choice IN ('continue', 'next')),
        response_latency_ms INTEGER NOT NULL,
        submitted_at TEXT NOT NULL,
        UNIQUE(trial_id, probe_index)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS events (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        trial_id BIGINT NOT NULL REFERENCES trials(id),
        event_type TEXT NOT NULL,
        video_time DOUBLE PRECISION,
        client_wall_time TEXT,
        server_received_at TEXT NOT NULL,
        details_json TEXT
    )
    """,
)


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def get_db() -> psycopg.Connection[dict[str, Any]]:
    """Return one PostgreSQL connection for the current Flask request."""
    if "db" not in g:
        if not DATABASE_URL:
            raise RuntimeError("DATABASE_URL must be set to a PostgreSQL connection URL.")
        g.db = psycopg.connect(DATABASE_URL, row_factory=dict_row)
    return g.db


@app.teardown_appcontext
def close_db(_error: Exception | None) -> None:
    db = g.pop("db", None)
    if db is not None:
        db.close()


def init_db() -> None:
    """Create the schema on a new PostgreSQL database if it is not present."""
    db = get_db()
    for statement in SCHEMA_STATEMENTS:
        db.execute(statement)
    db.commit()


def load_stimuli() -> list[dict[str, Any]]:
    with STIMULI_PATH.open(encoding="utf-8") as stream:
        return json.load(stream)["videos"]


def ensure_session() -> str:
    """Create a browser-local anonymous study session on its first visit."""
    if "participant_id" in session:
        return session["participant_id"]

    participant_id = secrets.token_urlsafe(16)
    stimuli = load_stimuli()
    # Shuffle video order once per participant. Each video keeps all its probes.
    rng = Random(secrets.randbits(64))
    rng.shuffle(stimuli)

    db = get_db()
    db.execute(
        "INSERT INTO sessions (id, trial_order_json, started_at) VALUES (%s, %s, %s)",
        (participant_id, json.dumps(stimuli), utc_now()),
    )
    db.commit()
    session["participant_id"] = participant_id
    return participant_id


def current_trial(participant_id: str) -> dict[str, Any] | None:
    db = get_db()
    study_session = db.execute(
        "SELECT * FROM sessions WHERE id = %s", (participant_id,)
    ).fetchone()
    if study_session is None:
        abort(404)

    order = json.loads(study_session["trial_order_json"])
    position = study_session["current_position"]
    if position >= len(order):
        return None

    trial = db.execute(
        "SELECT * FROM trials WHERE session_id = %s AND position = %s",
        (participant_id, position),
    ).fetchone()
    if trial is not None:
        return trial

    stimulus = order[position]
    probes = sorted(stimulus["probe_candidates"], key=lambda probe: probe["time"])
    trial = db.execute(
        """
        INSERT INTO trials
          (session_id, position, video_id, video_title, youtube_id,
           probe_plan_json, created_at)
        VALUES (%s, %s, %s, %s, %s, %s, %s)
        RETURNING *
        """,
        (
            participant_id,
            position,
            stimulus["id"],
            stimulus["title"],
            stimulus["youtube_id"],
            json.dumps(probes),
            utc_now(),
        ),
    ).fetchone()
    db.commit()
    return trial


def owned_trial(trial_id: int) -> dict[str, Any]:
    """Retrieve a trial only when it belongs to the current participant."""
    participant_id = ensure_session()
    trial = get_db().execute(
        "SELECT * FROM trials WHERE id = %s AND session_id = %s",
        (trial_id, participant_id),
    ).fetchone()
    if trial is None:
        abort(404)
    return trial


@app.before_request
def initialise_database() -> None:
    init_db()


@app.get("/")
def study() -> str:
    ensure_session()
    return render_template("study.html")


@app.get("/api/trial/current")
def get_current_trial():
    participant_id = ensure_session()
    trial = current_trial(participant_id)
    if trial is None:
        return jsonify({"complete": True})

    probes = json.loads(trial["probe_plan_json"])
    row = get_db().execute(
        """
        SELECT COALESCE(MAX(probe_index), -1) + 1 AS next_probe_index
        FROM responses
        WHERE trial_id = %s
        """,
        (trial["id"],),
    ).fetchone()

    return jsonify(
        {
            "complete": False,
            "trial_id": trial["id"],
            "title": trial["video_title"],
            "youtube_id": trial["youtube_id"],
            "probes": probes,
            "next_probe_index": row["next_probe_index"],
        }
    )


@app.post("/api/event")
def log_event():
    data = request.get_json(force=True)
    trial = owned_trial(int(data["trial_id"]))
    event_type = str(data["event_type"])
    allowed = {"video_started", "probe_shown", "response_submitted", "video_ended", "player_error"}
    if event_type not in allowed:
        return jsonify({"error": "Unknown event type"}), 400

    db = get_db()
    db.execute(
        """
        INSERT INTO events (trial_id, event_type, video_time, client_wall_time,
                            server_received_at, details_json)
        VALUES (%s, %s, %s, %s, %s, %s)
        """,
        (
            trial["id"],
            event_type,
            data.get("video_time"),
            data.get("client_wall_time"),
            utc_now(),
            json.dumps(data.get("details", {})),
        ),
    )
    db.commit()
    return jsonify({"ok": True})


@app.post("/api/response")
def save_response():
    data = request.get_json(force=True)
    trial = owned_trial(int(data["trial_id"]))
    probe_index = data.get("probe_index")
    choice = data.get("choice")
    latency = data.get("response_latency_ms")

    if (
        not isinstance(probe_index, int)
        or choice not in {"continue", "next"}
        or not isinstance(latency, int)
        or latency < 0
    ):
        return jsonify({"error": "Invalid response"}), 400

    probes = json.loads(trial["probe_plan_json"])
    if probe_index < 0 or probe_index >= len(probes):
        return jsonify({"error": "Invalid probe index"}), 400

    probe = probes[probe_index]
    db = get_db()
    try:
        db.execute(
            """
            INSERT INTO responses
              (trial_id, probe_index, planned_probe_time, probe_category,
               choice, response_latency_ms, submitted_at)
            VALUES (%s, %s, %s, %s, %s, %s, %s)
            """,
            (
                trial["id"],
                probe_index,
                probe["time"],
                probe["category"],
                choice,
                latency,
                utc_now(),
            ),
        )
        db.commit()
    except IntegrityError:
        # PostgreSQL marks a failed transaction as unusable until it is rolled back.
        db.rollback()
        return jsonify({"ok": True, "already_saved": True})

    return jsonify({"ok": True})


@app.post("/api/trial/next")
def advance_trial():
    data = request.get_json(force=True)
    trial = owned_trial(int(data["trial_id"]))
    db = get_db()
    db.execute("UPDATE trials SET ended_at = %s WHERE id = %s", (utc_now(), trial["id"]))
    db.execute(
        "UPDATE sessions SET current_position = current_position + 1 WHERE id = %s",
        (ensure_session(),),
    )
    db.commit()
    return jsonify({"ok": True})


@app.get("/admin/summary")
def admin_summary():
    """Password-protected inspection endpoint for the study owner."""
    admin_password = os.environ.get("ADMIN_PASSWORD")
    auth = request.authorization
    if (
        not admin_password
        or auth is None
        or auth.username != "admin"
        or not secrets.compare_digest(auth.password or "", admin_password)
    ):
        return Response(
            "Authentication required.",
            401,
            {"WWW-Authenticate": 'Basic realm="Study results"'},
        )

    rows = get_db().execute(
        """
        SELECT
            t.session_id,
            t.id AS trial_id,
            t.video_title,
            r.probe_index,
            r.planned_probe_time,
            r.probe_category,
            r.choice,
            r.response_latency_ms,
            r.submitted_at
        FROM trials AS t
        LEFT JOIN responses AS r ON r.trial_id = t.id
        ORDER BY t.id DESC, r.probe_index ASC
        """
    ).fetchall()
    return jsonify(rows)


if __name__ == "__main__":
    app.run(debug=True)
